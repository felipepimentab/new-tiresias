const struct codec_parameter* codec_contract_find(uint8_t id)
{
  const struct codec_parameter* parameter;

  if (id == 0U || id > CODEC_PARAMETER_COUNT) {
    return NULL;
  }

  parameter = &codec_contract[CODEC_PARAMETER_INDEX(id)];
  if (parameter->id != id) {
    return NULL;
  }

  return parameter;
}

BUILD_ASSERT(sizeof(struct codec_parameter) == 4U, "The fixed contract fingerprint requires four-byte entries");
BUILD_ASSERT(DSP_PARAMETER_ID_SOFT_CLIP_LUT == CODEC_PARAMETER_COUNT, "Parameter IDs must remain dense");
